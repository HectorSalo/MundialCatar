export function resolveThirdPlaceAssignment(
  qualifiedThirdGroups: string[],
): ThirdPlaceAssignment {
  const key = normalizeKey(qualifiedThirdGroups);
  const mapping = THIRD_PLACE_COMBINATIONS[key];

  if (!mapping) {
    throw new Error(
      `No existe mapping oficial para la combinación de terceros "${key}".`
    );
  }

  return mapping;
}

export function getAssignedThirdGroupForMatch(
  qualifiedThirdGroups: string[],
  matchNumber: ThirdPlaceMatchNumber,
): string {
  const assignment = resolveThirdPlaceAssignment(qualifiedThirdGroups);

  switch (matchNumber) {
    case 74: return assignment.match74;
    case 77: return assignment.match77;
    case 79: return assignment.match79;
    case 80: return assignment.match80;
    case 81: return assignment.match81;
    case 82: return assignment.match82;
    case 85: return assignment.match85;
    case 87: return assignment.match87;
    default:
      throw new Error(`Match ${matchNumber} no soportado para terceros.`);
  }
}